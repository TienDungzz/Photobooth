const make = (
  id: string,
  vi: string,
  en: string,
  mask: Slot['mask'],
  count: number,
  columns: number,
  rotation = 0,
): Layout => {
  const rows = Math.ceil(count / columns),
    gap = 0.045;
  const width = (0.8 - gap * (columns - 1)) / columns,
    height = (0.68 - gap * (rows - 1)) / rows;
  return {
    id,
    name: { vi, en },
    category: columns === 1 ? 'strip' : 'editorial',
    width: 1600,
    height: 2200,
    slots: Array.from({ length: count }, (_, i) => ({
      id: 'slot-' + i,
      x: 0.1 + (i % columns) * (width + gap),
      y: 0.15 + Math.floor(i / columns) * (height + gap),
      width,
      height,
      mask,
      rotation: i % 2 ? rotation : -rotation,
    })),
  };
};
// Shape proportions are authored in output pixels, rather than stretched into a generic grid.
const shaped = (
  id: string,
  vi: string,
  en: string,
  mask: Slot['mask'],
  width: number,
  height: number,
  boxes: [number, number, number, number][],
): Layout => ({
  id,
  name: { vi, en },
  category: width < height ? 'strip' : 'editorial',
  width,
  height,
  slots: boxes.map(([x, y, w, h], index) => ({
    id: `slot-${index}`,
    x: x / width,
    y: y / height,
    width: w / width,
    height: h / height,
    rotation: 0,
    mask,
  })),
});
