// One representative per motif; palette and placement variants no longer multiply the catalog.
export const extraFrames: Frame[] = motifs.map((motif) => {
  const variant = preferredPlacements[motif.id] ?? 'classic';
  const index = ['classic', 'scattered', 'corners'].indexOf(variant);
  return {
    id: `${motif.id}-${variant}`,
    name: {
      vi: `${motif.vi} · ${['Cổ điển', 'Bay bổng', 'Góc xinh'][index]}`,
      en: `${motif.en} · ${['Classic', 'Daydream', 'Corners'][index]}`,
    },
    pattern: motif.id,
    collection: motif.collection,
    color: index === 1 ? 'cream' : motif.color,
    variant,
    background: index === 1 ? '#fff9ee' : motif.background,
    accent: motif.accent,
    ink: motif.color === 'dark' && index !== 1 ? '#f5e9d0' : '#65534e',
    style: 'pastel',
    stamp: ['Made of little happy things', 'A page from our story', 'A moment worth keeping'][
      index
    ],
  };
});
